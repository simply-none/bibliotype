/**
 * 工具条使用说明的数据契约（可插拔）
 *
 * 设计意图：**说明是数据，不是注释**。
 * - 「按钮做什么」属于消费方（demo 工具条），命令本身的前置条件 / 落点属于插件包
 *   `@bibliotype/editor` 与 `@bibliotype/classical/editor` 的 JSDoc（那里是权威口径）；
 * - 本文件只描述「点这个按钮，用户该怎么操作」，由 `ToolbarUsageTip` 渲染成
 *   **鼠标悬浮卡片**（不用原生 title —— 原生提示延迟约 1s、长文案会被截断，
 *   也装不下「前提 / 落点 / 属性 / 限制」四类信息）；
 * - `ToolbarAction.usage` 为**可选**字段：传了就有悬浮说明，不传则该按钮完全退回
 *   原始行为（不注册悬浮、不渲染卡片），便于把工具条抽成公共组件后由使用方决定。
 */

/** 单个功能入口的使用说明（各字段均为「差异点」，通用前提写在该项所在分组的注释里） */
export interface ToolbarUsage {
  /** 一句话用途：点了会发生什么 */
  use: string;
  /** 操作前提：对选区 / 光标位置的要求（缺省表示任意位置可用） */
  require?: string;
  /** 生效落点：结果出现在光标处、当前段之后、还是包裹选区 */
  where?: string;
  /** 需在右侧属性栏补录的属性（插入后可改，不是插入时录入） */
  attrs?: string;
  /** 快捷键（缺省表示无键盘入口） */
  key?: string;
  /** 已知限制 / 点了没反应的原因 */
  limit?: string;
}
